S = []


def sh(sid, prompt, motion, say=None, who=None, ref=None, sfx=None, look=None,
       seconds=None, chain=None, motions=None, tin=None, in_dur=None, titles=None,
       from_prev=False, quality=False, seed=None):
    d = collections.OrderedDict(id=sid)
    if tin:
        d["in"] = tin
    if in_dur:
        d["in_dur"] = in_dur
    if look:
        d["look"] = look
    if ref:
        d["ref"] = ref
    if chain:
        d["chain"] = chain
    if seconds:
        d["seconds"] = seconds
    if from_prev:
        d["from_prev"] = True
    if quality:
        d["quality"] = True
    if seed:
        d["seed"] = seed
    d["prompt"] = prompt
    d["motion"] = motion
    for i, m in enumerate(motions or [], start=2):
        d[f"motion{i}"] = m
    if say:
        d["say"] = say
        if who:
            d["who"] = who
    if sfx:
        d["sfx"] = sfx
    if titles:
        d["titles"] = titles
    S.append(d)


