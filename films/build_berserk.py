"""Build films/berserk.json - THE GOLDEN AGE, a narrated summary of Berserk season 1.

Run:  python films/build_berserk.py

Written as a builder rather than raw JSON because a 20-minute film is ~120 shots and the
shot list needs to stay readable and editable. Everything the pipeline understands is
documented in FILMCRAFT.md and craft/.

Design decisions, all deliberate:

* CHARACTER CONSISTENCY - every shot with a person carries `ref`, so the keyframe is
  generated by Qwen-Image-Edit 2511 conditioned on that character's canonical sheet. The
  face is never re-invented from words. See craft/CINEMATOGRAPHY.md section 8.
* ACTION IS CHAINED - fights use `chain: 3-4` with per-link `motion2/3/4`, giving 24-32s
  continuous takes with real choreography instead of 4s of averaged flailing.
* THE STORY IS THE FRIENDSHIP - the arc is Guts and Griffith, so the beats that get room
  are the two duels, the campfire, the overheard sentence, and the departure. Battles are
  spectacle in service of that, and the political plot is carried by narration.
* CONTENT - this is a summary of a famously brutal work. Violence is staged in silhouette
  and aftermath. The Eclipse is handled by implication: the horror is on Guts' face and in
  what the narration will not say. No sexual violence is depicted or described.
* RIGHTS - original narration and dialogue, and character designs described in our own
  terms rather than reproduced. Names are used as any summary would.
"""
