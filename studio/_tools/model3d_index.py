#!/usr/bin/env python3
"""studio/_tools/model3d_index.py - the payload behind /model3d.

    python3 studio/_tools/model3d_index.py                 a human summary
    python3 studio/_tools/model3d_index.py --json          the payload the page reads
    python3 studio/_tools/model3d_index.py --character TERRA
    python3 studio/_tools/model3d_index.py --check         exit 1 if any asset is missing

WHAT THIS IS. Three agents produced the 3D work for TERRA and left it on disk as a
sample tree, two JSON reports, a markdown verdict and 885 MB of meshes and renders.
Nothing in the app reached any of it. This assembles that tree into one payload so
/model3d can show it, and so the next character's pipeline is discovered rather than
hand-listed.

WHAT IT DOES NOT DO. It measures nothing. Every number it returns is read out of
studio/samples/<slug>_3d/mesh/REPORT.json, which studio/_tools/terra_mesh.py wrote from
studio/_tools/mesh_doctor.py's own JSON. If a number here disagrees with a mesh, the
report is stale - regenerate it, do not edit this file. The only things authored here are
the VERDICT/FAILURE note tables below, and each one carries the section of
mesh/VERDICT.md it was read out of so it can be checked.

DISCOVERY. A character has a 3D pipeline if studio/samples/<id.lower()>_3d/ exists. That
is the whole contract - run the pipeline for NIKA into studio/samples/nika_3d/ with the
same layout and this tool finds her with no edit. Layout:

    <slug>_3d/source/RECOMMENDATION.json     which image to feed, and why
    <slug>_3d/source/*.png                   the matted candidates
    <slug>_3d/source/multiview_qwen/*.png    the four cardinals
    <slug>_3d/source/evidence/*.jpg          the sweeps behind the recommendation
    <slug>_3d/mesh/REPORT.json               every candidate, generated and measured
    <slug>_3d/mesh/VERDICT.md                which mesh won, written after looking
    <slug>_3d/mesh/*.glb                     the meshes
    <slug>_3d/mesh/views/*.jpg|*.mp4         orbit strips, head close-ups, turntables
    <slug>_3d/mesh/print/*.stl|*.3mf         the sliceable deliverables

EVERY ASSET IS CHECKED AGAINST THE FILESYSTEM. A candidate that names a render which is
not there is reported in `missing` rather than shipped as a broken <img>, because the
cast page used to render a green tick for a string being non-empty and that is exactly
how a page ends up lying.
"""
