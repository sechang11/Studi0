def character(cid):
    cid = str(cid or "").strip()
    cards = _cards()
    if cid not in cards:
        # tolerate a lowercase or slug spelling
        hit = next((k for k in cards if k.lower() == cid.lower()), None)
        if not hit:
            return None
        cid = hit
    d = _pipeline_dir(cid)
    if not os.path.isdir(d):
        return {"id": cid, "name": cards[cid].get("name") or cid, "state": "none",
                "root": None, "stages": STAGES, "failures": FAILURES}
    root_url = "/samples/" + os.path.basename(d)
    a = Assets(d, root_url)
    report = _read_json(os.path.join(d, "mesh", "REPORT.json"), {}) or {}
    cands = _candidates(a, d, report)
    out = {
        "id": cid,
        "name": cards[cid].get("name") or cid,
        "state": "printable" if (_listdir(os.path.join(d, "print"), [".stl", ".3mf"])
                                 or _listdir(os.path.join(d, "mesh", "print"),
                                             [".stl", ".3mf"])) else "meshed",
        "root": root_url,
        "rel": os.path.relpath(d, ROOT).replace(os.sep, "/"),
        "stages": STAGES,
        "source": _source(a, d, report),
        "prep": report.get("prep") or {},
        "candidates": cands,
        "splats": _splats(a, d, report),
        "deliverables": _deliverables(a, d),
        "audit": _audit(cands),
        "failures": _failures(a),
        "docs": {
            "verdict": _read_text(os.path.join(d, "mesh", "VERDICT.md")),
            "verdict_rel": os.path.relpath(os.path.join(d, "mesh", "VERDICT.md"),
                                           ROOT).replace(os.sep, "/"),
            "recipe_rel": "craft/CHARACTER_TO_PRINT.md",
            "printing_rel": "craft/PRINTING.md",
        },
        "totals": {
            "candidates": len(cands),
            "failed": len([c for c in cands if c["state"] == "fail"]),
            "assets": a.n,
            "asset_bytes": a.bytes,
        },
        "missing": a.missing,
    }
    return out


