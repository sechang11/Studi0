def _read_json(p, default=None):
    try:
        with open(p, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def _read_text(p):
    try:
        with open(p, encoding="utf-8", errors="replace") as f:
            return f.read()
    except Exception:
        return None


class Assets(object):
    """Resolve a path inside one character's 3D tree to a /samples URL, or record it as
    missing. Nothing reaches the page without passing through here, which is the whole
    reason the page cannot show a broken image."""

    def __init__(self, root_abs, root_url):
        self.root_abs = root_abs
        self.root_url = root_url
        self.missing = []
        self.bytes = 0
        self.n = 0

    def url(self, rel, required=True):
        if not rel:
            return None
        p = os.path.join(self.root_abs, rel)
        if not os.path.isfile(p):
            if required:
                self.missing.append(rel)
            return None
        self.n += 1
        self.bytes += os.path.getsize(p)
        return self.root_url + "/" + rel.replace(os.sep, "/")

    def file(self, rel, required=True):
        """Like url(), but returns {url, bytes, name} - for anything with a download link,
        because a 133 MB button that does not say so is a trap."""
        u = self.url(rel, required)
        if not u:
            return None
        p = os.path.join(self.root_abs, rel)
        return {"url": u, "bytes": os.path.getsize(p),
                "name": os.path.basename(rel),
                "ext": os.path.splitext(rel)[1].lower()}


def _listdir(d, suffixes=None):
    if not os.path.isdir(d):
        return []
    out = []
    for fn in sorted(os.listdir(d)):
        if suffixes and not fn.lower().endswith(tuple(suffixes)):
            continue
        if os.path.isfile(os.path.join(d, fn)):
            out.append(fn)
    return out


