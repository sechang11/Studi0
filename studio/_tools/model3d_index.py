def _candidates(a, d, report):
    out = []
    for c in report.get("candidates") or []:
        name = c.get("name") or ""
        row = dict(c)
        # Absolute paths in REPORT.json are the mesh stage's own; re-resolve by filename
        # so a moved tree still works and a missing render is reported rather than shown.
        row["orbit"] = a.url("mesh/views/%s_orbit.jpg" % name, required=False)
        row["head"] = a.url("mesh/views/%s_head.jpg" % name, required=False)
        row["turntable"] = a.url("mesh/views/%s_turntable.mp4" % name, required=False)
        row["glb"] = a.file("mesh/%s.glb" % name, required=False)
        row["glb_fixed"] = a.file("mesh/%s_fixed.glb" % name, required=False)
        row.pop("orbit_sheet", None)
        row.pop("head_sheet", None)
        state, note, src = NOTES.get(name, ("ok", None, None))
        row["state"] = state
        row["note"] = note
        row["note_src"] = src
        reps = []
        for r in REPAIRS.get(name, []):
            rr = dict(r)
            rr["glb"] = a.file("mesh/" + r["glb"], required=False)
            rr["orbit"] = a.url("mesh/views/" + r["orbit"], required=False) \
                if r.get("orbit") else None
            rr["head"] = a.url("mesh/views/" + r["head"], required=False) \
                if r.get("head") else None
            rr["turntable"] = a.url("mesh/views/" + r["turntable"], required=False) \
                if r.get("turntable") else None
            reps.append(rr)
        row["repairs"] = reps
        row["shipped_thickness"] = SHIPPED_THICKNESS.get(name)
        out.append(row)
    return out


def _splats(a, d, report):
    out = []
    for name, s in sorted((report.get("splat") or {}).items()):
        out.append({
            "name": name,
            "gaussians": s.get("num_gaussians"),
            "wall_s": s.get("wall_s"),
            "vram_peak_mib": (s.get("vram") or {}).get("peak_mib"),
            "mp4": a.url("mesh/%s.mp4" % name, required=False),
            "spz": a.file("mesh/%s.spz" % name, required=False),
        })
    return out


def _deliverables(a, d):
    """TWO STAGES WRITE DELIVERABLES AND ONLY THE SECOND IS SLICEABLE.

    mesh/print/ is the mesh stage's export - correct topology, but the figure stands on
    two boot tips (148 mm2 of bed contact, measured). print/ is mesh_prep.py's later
    output: the same figure fused onto a 50 mm plinth (1,953 mm2). This function was
    written before the second stage existed and listed only the first, which meant the
    page offered a model that falls off the plate and labelled it THE DELIVERABLE.
    Both stages are listed - the bare one is what you take to re-pose or re-base her -
    but print/ is scanned first and carries the winner."""
    out = []
    for sub in ("print", "print/alt", "mesh/print"):
        subdir = os.path.join(d, *sub.split("/"))
        for fn in _listdir(subdir, [".stl", ".3mf", ".obj", ".glb"]):
            f = a.file(sub + "/" + fn)
            if not f:
                continue
            state, note = DELIVERABLE_NOTES.get(fn, ("ok", None))
            f["state"] = state
            f["note"] = note
            f["stage"] = "bare" if sub.startswith("mesh/") else "plinth"
            f["mime"] = MIME3D.get(f["ext"], "application/octet-stream")
            out.append(f)
    # Winner files first, then the alternates. Without the ALT test an alphabetically
    # early alternate lands above the thing you are meant to download.
    out.sort(key=lambda f: (0 if f["state"] == "win" else 1 if f["state"] == "ok" else 2,
                            1 if f["name"].startswith("ALT") else 0, f["name"]))
    return out


def _failures(a):
    """Resolve the failure gallery's pictures to URLs.

    They are relative paths in the FAILURES table above, and shipping them unresolved is
    exactly what happened the first time - the page rendered ten captions and no pictures,
    which is worse than useless on the section whose whole point is what a wrong one looks
    like. Every path goes through Assets like everything else, so one that is not on disk
    comes back None and the page draws the entry without it rather than a broken image."""
    out = []
    for f in FAILURES:
        g = dict(f)
        g["image"] = a.url(f["image"], required=False)
        if f.get("image2"):
            g["image2"] = a.url(f["image2"], required=False)
        out.append(g)
    return out


